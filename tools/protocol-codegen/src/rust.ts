import { Array, Record, String, pipe } from "effect";
import { SERVER_FLAGS } from "protocol";

const HEADER = "// @generated by tools/protocol-codegen. Do not edit.";

const constantOf = ([key, flag]: readonly [string, string]): string =>
  `pub const ${String.toUpperCase(String.camelToSnake(key))}_FLAG: &str = "--${flag}";`;

const rust = (): string =>
  Array.join(
    [HEADER, "", ...pipe(Record.toEntries(SERVER_FLAGS), Array.map(constantOf)), ""],
    "\n",
  );

export { rust };
